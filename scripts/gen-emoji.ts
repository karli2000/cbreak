// Generates plugin/hooks/lib/emoji-data.ts (the shortcode table the mod uses) from the pinned gemoji package.
// An installed mod cannot load npm packages, so the table is committed; tests/unit/emoji.test.ts checks it is fresh.
import { gemoji } from 'gemoji'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import pkg from 'gemoji/package.json' with { type: 'json' }

export const EMOJI_DATA_PATH = join(import.meta.dir, '../plugin/hooks/lib/emoji-data.ts')

/** The exact text of emoji-data.ts: every gemoji name (all aliases), sorted, first emoji wins. */
export function renderEmojiData(): string {
  const byName = new Map<string, string>()
  for (const g of gemoji) for (const n of g.names) if (!byName.has(n)) byName.set(n, g.emoji)
  const rows = [...byName].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  return (
    `// generated by scripts/gen-emoji.ts from gemoji ${pkg.version}; do not edit\n` +
    `export const SHORTCODES: ReadonlyArray<readonly [name: string, emoji: string]> = [\n` +
    rows.map(([n, e]) => `  [${JSON.stringify(n)}, ${JSON.stringify(e)}],\n`).join('') +
    `]\n`
  )
}

if (import.meta.main) {
  writeFileSync(EMOJI_DATA_PATH, renderEmojiData())
  console.log(`wrote ${EMOJI_DATA_PATH}`)
}
